from __future__ import annotations

from dataclasses import dataclass, field
from typing import List, Dict, Any, Optional
from pathlib import Path
import os
import tempfile
import io

from docx import Document
from docx.shared import Pt, Inches, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib import colors
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.cidfonts import UnicodeCIDFont


_SUPPORTED_FORMATS = {"docx", "pdf"}


@dataclass
class GeneratedReport:
    filename: str
    format: str
    bytes: bytes
    size_bytes: int


def _ensure_dir(path: str) -> None:
    Path(path).parent.mkdir(parents=True, exist_ok=True)


def _register_pdf_font():
    try:
        pdfmetrics.registerFont(UnicodeCIDFont("HeiseiKakuGo-W5"))
        return "HeiseiKakuGo-W5"
    except Exception:
        return "Helvetica"


def generate_nlp_report_docx(
    text: str,
    analysis_result: Dict[str, Any],
    title: str = "KANAME NLP Analysis Report",
    author: str = "KANAME [要]",
    include_bilingual: bool = True,
) -> bytes:
    doc = Document()

    style = doc.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(11)

    title_p = doc.add_heading(title, level=0)
    title_p.alignment = WD_ALIGN_PARAGRAPH.CENTER

    meta = doc.add_paragraph()
    meta.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = meta.add_run(f"Generated by {author}")
    run.italic = True
    run.font.size = Pt(10)
    run.font.color.rgb = RGBColor(0x55, 0x55, 0x55)

    doc.add_heading("1. Input Text (入力文章)", level=1)
    doc.add_paragraph(text)

    doc.add_heading("2. Analysis Summary (解析概要)", level=1)
    summary_table = doc.add_table(rows=1, cols=2)
    summary_table.style = "Light Grid Accent 1"
    hdr = summary_table.rows[0].cells
    hdr[0].text = "Item"
    hdr[1].text = "Value"

    def add_row(name: str, value: str):
        row = summary_table.add_row().cells
        row[0].text = name
        row[1].text = value

    mode = analysis_result.get("mode", "C")
    add_row("Split Mode (分割モード)", f"Mode {mode}")
    add_row("Token Count (トークン数)", str(analysis_result.get("token_count", 0)))
    add_row("Wakati-gaki (分かち書き)", analysis_result.get("wakati", ""))
    add_row("Kana Only (カナ読み)", analysis_result.get("kana_only_text", ""))
    add_row("Nouns (名詞)", ", ".join(analysis_result.get("noun_list", []) or []))
    add_row("Verbs (動詞・辞書形)", ", ".join(analysis_result.get("verb_list", []) or []))
    add_row("Adjectives (形容詞・辞書形)", ", ".join(analysis_result.get("adjective_list", []) or []))

    doc.add_heading("3. POS Distribution (品詞分布)", level=1)
    pos = analysis_result.get("pos_counts", {})
    if pos:
        pos_table = doc.add_table(rows=1, cols=3)
        pos_table.style = "Light Grid Accent 1"
        ph = pos_table.rows[0].cells
        ph[0].text = "POS (日本語)"
        ph[1].text = "POS (English)"
        ph[2].text = "Count"
        label_map = {
            "名詞": "Noun", "動詞": "Verb", "形容詞": "Adjective",
            "副詞": "Adverb", "助詞": "Particle", "助動詞": "Auxiliary Verb",
            "接尾辞": "Suffix", "接頭辞": "Prefix", "連体詞": "Adnominal",
            "感動詞": "Interjection", "記号": "Symbol", "補助記号": "Supplementary Symbol",
            "接続詞": "Conjunction", "形状詞": "Adjectival Noun", "準形状詞": "Quasi-Adjectival",
            "空白": "Whitespace", "終助詞": "Sentence-Ending Particle", "間投詞": "Interjection",
            "係助詞": "Binding Particle", "格助詞": "Case Particle", "副助詞": "Adverbial Particle",
            "接続助詞": "Conjunctive Particle", "並立助詞": "Coordinate Particle",
        }
        for k, v in sorted(pos.items(), key=lambda kv: -kv[1]):
            r = pos_table.add_row().cells
            r[0].text = k
            r[1].text = label_map.get(k, k)
            r[2].text = str(v)
    else:
        doc.add_paragraph("(no POS counts available)")

    doc.add_heading("4. Full Tokens (トークン一覧)", level=1)
    tokens = analysis_result.get("tokens", []) or []
    if tokens:
        tok_table = doc.add_table(rows=1, cols=5)
        tok_table.style = "Light Grid Accent 1"
        th = tok_table.rows[0].cells
        th[0].text = "#"
        th[1].text = "Surface (表層形)"
        th[2].text = "POS (品詞)"
        th[3].text = "Reading (読み)"
        th[4].text = "Dictionary Form (基本形)"
        for i, t in enumerate(tokens, start=1):
            r = tok_table.add_row().cells
            r[0].text = str(i)
            r[1].text = str(t.get("surface", ""))
            r[2].text = ", ".join(t.get("pos") or [])
            r[3].text = str(t.get("reading", ""))
            r[4].text = str(t.get("dictionary_form", ""))
    else:
        doc.add_paragraph("(no tokens available)")

    if include_bilingual:
        doc.add_heading("5. Notes (備考)", level=1)
        notes = (
            "This report was generated automatically by the KANAME [要] AI system. "
            "Morphological analysis powered by SudachiPy (Works Applications / SudachiDict-core). "
            "日本語形態素解析はSudachiPyにより実行されました。"
        )
        doc.add_paragraph(notes)

    bio = io.BytesIO()
    doc.save(bio)
    return bio.getvalue()


def generate_nlp_report_pdf(
    text: str,
    analysis_result: Dict[str, Any],
    title: str = "KANAME NLP Analysis Report",
    author: str = "KANAME [要]",
    include_bilingual: bool = True,
) -> bytes:
    bio = io.BytesIO()
    doc = SimpleDocTemplate(bio, pagesize=A4, leftMargin=20*mm, rightMargin=20*mm, topMargin=20*mm, bottomMargin=20*mm)
    font = _register_pdf_font()
    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "KTitle", parent=styles["Title"], fontName=font, fontSize=20, leading=26, alignment=1, spaceAfter=6)
    h1 = ParagraphStyle("KH1", parent=styles["Heading1"], fontName=font, fontSize=14, leading=18, spaceBefore=8, spaceAfter=4)
    body = ParagraphStyle("KBody", parent=styles["BodyText"], fontName=font, fontSize=10, leading=14)
    meta = ParagraphStyle("KMeta", parent=body, alignment=1, textColor=colors.grey)

    story = []
    story.append(Paragraph(title, title_style))
    story.append(Paragraph(f"Generated by {author}", meta))
    story.append(Spacer(1, 6*mm))

    story.append(Paragraph("1. Input Text (入力文章)", h1))
    story.append(Paragraph(text.replace("\n", "<br/>"), body))
    story.append(Spacer(1, 3*mm))

    story.append(Paragraph("2. Analysis Summary (解析概要)", h1))
    rows = [["Item", "Value"]]
    mode = analysis_result.get("mode", "C")
    rows.append(["Split Mode (分割モード)", f"Mode {mode}"])
    rows.append(["Token Count (トークン数)", str(analysis_result.get("token_count", 0))])
    rows.append(["Wakati-gaki (分かち書き)", analysis_result.get("wakati", "")])
    rows.append(["Kana Only (カナ読み)", analysis_result.get("kana_only_text", "")])
    rows.append(["Nouns (名詞)", ", ".join(analysis_result.get("noun_list", []) or [])])
    rows.append(["Verbs (動詞)", ", ".join(analysis_result.get("verb_list", []) or [])])
    rows.append(["Adjectives (形容詞)", ", ".join(analysis_result.get("adjective_list", []) or [])])
    rows_p = [[Paragraph(str(c), body) for c in row] for row in rows]
    t = Table(rows_p, colWidths=[55*mm, 110*mm])
    t.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (-1, -1), font),
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f3460")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(t)
    story.append(Spacer(1, 4*mm))

    story.append(Paragraph("3. POS Distribution (品詞分布)", h1))
    pos = analysis_result.get("pos_counts", {})
    if pos:
        pos_rows = [["POS (日本語)", "POS (English)", "Count"]]
        pos_label_map = {
            "名詞": "Noun", "動詞": "Verb", "形容詞": "Adjective",
            "副詞": "Adverb", "助詞": "Particle", "助動詞": "Auxiliary Verb",
            "接尾辞": "Suffix", "接頭辞": "Prefix", "連体詞": "Adnominal",
            "感動詞": "Interjection", "記号": "Symbol", "補助記号": "Supplementary Symbol",
            "接続詞": "Conjunction", "形状詞": "Adjectival Noun", "準形状詞": "Quasi-Adjectival",
            "空白": "Whitespace", "終助詞": "Sentence-Ending Particle", "間投詞": "Interjection",
            "係助詞": "Binding Particle", "格助詞": "Case Particle", "副助詞": "Adverbial Particle",
            "接続助詞": "Conjunctive Particle", "並立助詞": "Coordinate Particle",
        }
        for k, v in sorted(pos.items(), key=lambda kv: -kv[1]):
            pos_rows.append([k, pos_label_map.get(k, k), str(v)])
        pos_rows_p = [[Paragraph(str(c), body) for c in row] for row in pos_rows]
        pt = Table(pos_rows_p, colWidths=[50*mm, 70*mm, 25*mm], repeatRows=1)
        pt.setStyle(TableStyle([
            ("FONTNAME", (0, 0), (-1, -1), font),
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#0f3460")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ]))
        story.append(pt)
    else:
        story.append(Paragraph("(no POS counts available)", body))
    story.append(Spacer(1, 4*mm))

    story.append(Paragraph("4. Full Tokens (トークン一覧)", h1))
    tokens = analysis_result.get("tokens", []) or []
    tok_rows = [["#", "Surface", "POS", "Reading", "DictForm"]]
    for i, t in enumerate(tokens, start=1):
        tok_rows.append([
            str(i),
            str(t.get("surface", "")),
            "/".join(t.get("pos") or [])[:40],
            str(t.get("reading", "")),
            str(t.get("dictionary_form", "")),
        ])
    tok_rows_p = [[Paragraph(str(c), body) for c in row] for row in tok_rows]
    tt = Table(tok_rows_p, colWidths=[10*mm, 30*mm, 55*mm, 30*mm, 40*mm], repeatRows=1)
    tt.setStyle(TableStyle([
        ("FONTNAME", (0, 0), (-1, -1), font),
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#16213e")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.grey),
    ]))
    story.append(tt)

    if include_bilingual:
        story.append(Spacer(1, 5*mm))
        story.append(Paragraph("5. Notes (備考)", h1))
        story.append(Paragraph(
            "Report generated by KANAME [要] — AI-Powered Japanese Language &amp; Productivity Intelligence System. "
            "Morphological analysis powered by SudachiPy / SudachiDict-core.",
            body,
        ))

    doc.build(story)
    return bio.getvalue()


def generate_nlp_report(
    text: str,
    analysis_result: Dict[str, Any],
    title: str = "KANAME NLP Analysis Report",
    author: str = "KANAME [要]",
    include_bilingual: bool = True,
    doc_format: str = "docx",
    output_dir: Optional[str] = None,
) -> GeneratedReport:
    fmt = (doc_format or "docx").lower()
    if fmt not in _SUPPORTED_FORMATS:
        raise ValueError(f"Unsupported format '{doc_format}'. Supported: {sorted(_SUPPORTED_FORMATS)}")

    safe_title = "".join(c if c.isalnum() or c in "-_ " else "_" for c in title).strip().replace(" ", "_") or "report"
    filename = f"{safe_title}.{fmt}"

    if fmt == "docx":
        payload = generate_nlp_report_docx(
            text=text,
            analysis_result=analysis_result,
            title=title,
            author=author,
            include_bilingual=include_bilingual,
        )
    else:
        payload = generate_nlp_report_pdf(
            text=text,
            analysis_result=analysis_result,
            title=title,
            author=author,
            include_bilingual=include_bilingual,
        )

    if output_dir:
        _ensure_dir(os.path.join(output_dir, filename))
        with open(os.path.join(output_dir, filename), "wb") as f:
            f.write(payload)

    return GeneratedReport(
        filename=filename,
        format=fmt,
        bytes=payload,
        size_bytes=len(payload),
    )
